const byId = new Map(STICKERS.map(s => [s.id, s]));
export const sticker = id => byId.get(id);

// For the tray. Art data only, never child input, so the string is safe to use as markup.
export function svg(id, sizeCss, { paper = true } = {}) {
  const s = byId.get(id);
  if (!s) return '';
  const fill = s.solid || (paper ? PAPER : 'none');
  const line = (d, w, extra = '') => `<path d="${d}" fill="none" stroke="${NAVY}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"${extra}/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="${sizeCss}" height="${sizeCss}" aria-hidden="true" focusable="false">`
    + `<path d="${s.outline}" fill="${fill}" stroke="${NAVY}" stroke-width="${LINE_W}" stroke-linejoin="round" stroke-linecap="round"/>`
    + s.details.map(d => line(d, DETAIL_W)).join('')
    + s.hem.map(d => `<path d="${d}" fill="none" stroke="${THREAD}" stroke-width="${HEM_W}" stroke-linecap="round" stroke-dasharray="${HEM_DASH.join(' ')}"/>`).join('')
    + s.buttons.map(b => `<circle cx="${b.x}" cy="${b.y}" r="${b.r}" fill="${SUN}" stroke="${NAVY}" stroke-width="${BUTTON_LINE_W}"/>`).join('')
    + '</svg>';
}
